const assert = require("assert/strict");
const fs = require("fs");
const path = require("path");

const root = path.join(__dirname, "..");
const visibleFiles = [
  "src/app/collections/page.jsx",
  "src/app/collections/[slug]/page.jsx",
  "src/components/HomeClient.jsx",
  "src/components/Footer.jsx",
  "src/app/video/[...slug]/VideoPlayerClient.jsx",
  "src/app/trends/weekly/page.jsx",
  "src/app/not-found.jsx",
];
const bannedPhrases = [
  "quality gate",
  "growing collection",
  "publication threshold",
  "verified videos",
  "curated adult videos",
  "verified discovery",
  "why this video was selected",
  "discovery score",
  "source views",
  "source rating",
  "catalog sync",
  "generated by ai",
  "system maintenance",
  "limit exceeded",
];

for (const relativePath of visibleFiles) {
  const source = fs
    .readFileSync(path.join(root, relativePath), "utf8")
    .toLowerCase();
  for (const phrase of bannedPhrases) {
    assert.equal(
      source.includes(phrase),
      false,
      `${relativePath} exposes internal copy: ${phrase}`,
    );
  }
}

const collectionPage = fs.readFileSync(
  path.join(root, "src/app/collections/[slug]/page.jsx"),
  "utf8",
);
assert.equal(
  collectionPage.includes("collection.editorialIntro"),
  false,
  "Internal editorial text must not be rendered",
);
assert.equal(
  collectionPage.includes("collection.intent"),
  false,
  "Internal collection intent must not be rendered",
);

console.log("User-facing copy regression tests passed.");
